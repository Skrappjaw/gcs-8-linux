#!/usr/bin/env python3
"""Generate ucm2/USB-Audio/BOSS/GCS-8-HiFi.conf from the GCS-8 channel table.

    python3 tools/gen_hifi.py > ucm2/USB-Audio/BOSS/GCS-8-HiFi.conf

The table follows the BOSS Windows driver (RDIF1240.INF): 7 stereo outputs over 14 channels and
10 stereo inputs over 20, in driver order. Device comments are the driver's own names.
"""
from collections import namedtuple

Pair = namedtuple("Pair", "direction aux name")

HW_CHANNELS = {"Playback": 14, "Capture": 20}
PCM_NAME = {"Playback": "gcs8_stereo_out", "Capture": "gcs8_stereo_in"}
FORMAT = "FLOAT_LE"  # the only format the GCS-8 offers (48 kHz only)

_OUT = ["CH USB", "MAIN-AUX", "CH 1-AUX", "CH 2-AUX", "CH 3-AUX", "CH 4-AUX", "CH SOUND PAD"]
_IN = ["MAIN", "MONITOR", "CH 1", "CH 2", "CH 3", "CH 4", "CH USB", "CH MOBILE", "CH BLUETOOTH",
       "CH SOUND PAD"]
PAIRS = ([Pair("Playback", 2 * i, n) for i, n in enumerate(_OUT)]
         + [Pair("Capture", 2 * i, n) for i, n in enumerate(_IN)])


def _split_pcm(direction):
    hw = HW_CHANNELS[direction]
    pos = "".join(f"\t\t\tHWChannelPos{c} {'FL' if c % 2 == 0 else 'FR'}\n" for c in range(hw))
    return ("\t{\n"
            "\t\tSplitPCM {\n"
            f'\t\t\tName "{PCM_NAME[direction]}"\n'
            f"\t\t\tDirection {direction}\n"
            f"\t\t\tFormat {FORMAT}\n"
            "\t\t\tChannels 2\n"
            f"\t\t\tHWChannels {hw}\n"
            f"{pos}"
            "\t\t}\n"
            "\t}\n")


def _device(number, pair, priority):
    return (f'SectionDevice."Line{number}" {{\n'
            f'\tComment "{pair.name}"\n'
            "\n"
            "\tValue {\n"
            f"\t\t{pair.direction}Priority {priority}\n"
            "\t}\n"
            "\tMacro.pcm_split.SplitPCMDevice {\n"
            f'\t\tName "{PCM_NAME[pair.direction]}"\n'
            f"\t\tDirection {pair.direction}\n"
            "\t\tDevice 0\n"  # required by alsa-ucm-conf 1.2.10's macro, optional later
            f"\t\tHWChannels {HW_CHANNELS[pair.direction]}\n"
            "\t\tChannels 2\n"
            f"\t\tChannel0 {pair.aux}\n"
            f"\t\tChannel1 {pair.aux + 1}\n"
            "\t\tChannelPos0 FL\n"
            "\t\tChannelPos1 FR\n"
            "\t}\n"
            "}\n")


def render():
    parts = ["# BOSS GCS-8: one stereo device per channel pair, named as in the BOSS Windows driver.\n"
             "# Generated by tools/gen_hifi.py from its channel table.\n"
             "\n"
             'Include.pcm_split.File "/common/pcm/split.conf"\n'
             "\n"
             "Macro [\n"
             + _split_pcm("Playback") + _split_pcm("Capture")
             + "]\n"]
    # Priority falls in driver order, so CH USB is the default output and MAIN the default input.
    counts = {"Playback": 0, "Capture": 0}
    for number, pair in enumerate(PAIRS, start=1):
        counts[pair.direction] += 1
        priority = 100 * (len([p for p in PAIRS if p.direction == pair.direction]) - counts[pair.direction] + 1)
        parts.append("\n" + _device(number, pair, priority))
    return "".join(parts)


if __name__ == "__main__":
    print(render(), end="")
